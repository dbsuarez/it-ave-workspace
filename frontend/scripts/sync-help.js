// Builds src/features/help-guide.js (what the in-app Help shows) from docs/USER_GUIDE.md, the single source of the guide.
// Run `npm run help` after editing the guide. `npm run check` (and so start, pack and dist) fails when they differ.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const guidePath = path.join(root, '..', 'docs', 'USER_GUIDE.md');
const outPath = path.join(root, 'src', 'features', 'help-guide.js');

function generate() {
  const markdown = fs.readFileSync(guidePath, 'utf8').replace(/\r\n/g, '\n');
  return `// GENERATED by scripts/sync-help.js from docs/USER_GUIDE.md. Do not edit: change the guide, then run \`npm run help\`.
const HELP_GUIDE_MARKDOWN = ${JSON.stringify(markdown)};

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { HELP_GUIDE_MARKDOWN };
}
`;
}

if (require.main === module) {
  fs.writeFileSync(outPath, generate());
  console.log(`Wrote ${path.relative(root, outPath)} from docs/USER_GUIDE.md.`);
}

module.exports = { generate, outPath };
