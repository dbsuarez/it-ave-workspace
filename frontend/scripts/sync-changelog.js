// Builds src/features/changelog-data.js (what the app shows after an update) from CHANGELOG.md at the repository root.
// Run `npm run changelog` after editing the changelog; the test suite fails when they differ.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const changelogPath = path.join(root, '..', 'CHANGELOG.md');
const outPath = path.join(root, 'src', 'features', 'changelog-data.js');

function generate() {
  const markdown = fs.readFileSync(changelogPath, 'utf8').replace(/\r\n/g, '\n');
  return `// GENERATED by scripts/sync-changelog.js from CHANGELOG.md. Do not edit: change the changelog, then run \`npm run changelog\`.
const CHANGELOG_MARKDOWN = ${JSON.stringify(markdown)};

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { CHANGELOG_MARKDOWN };
}
`;
}

if (require.main === module) {
  fs.writeFileSync(outPath, generate());
  console.log(`Wrote ${path.relative(root, outPath)} from CHANGELOG.md.`);
}

module.exports = { generate, outPath, changelogPath };
